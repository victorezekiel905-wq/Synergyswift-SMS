// Joins every migration from a starting file onward into one SQL file that can
// be pasted into the Supabase SQL editor in a single run.
// Usage: node scripts/bundle-update.mjs 20260101002400   (default: 20260101002400)
// Each migration is idempotent, so running the bundle twice is safe.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(root, "supabase", "migrations");
const from = process.argv[2] ?? "20260101002400";
const files = fs.readdirSync(dir).filter(f => f.endsWith(".sql") && f >= from).sort();
const out = path.join(root, "supabase", "updates", "RUN_THIS_UPDATE.sql");
fs.mkdirSync(path.dirname(out), { recursive: true });
const parts = files.map(f => `-- ===== ${f} =====\n${fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()}\n`);
fs.writeFileSync(out, `-- EduClass Fusion database update. Paste the whole file into the Supabase SQL editor and run it once.\n-- Contains: ${files.join(", ")}\n-- Safe to run again (every part is idempotent). Generated by scripts/bundle-update.mjs.\n\n${parts.join("\n")}`);
console.log(`bundle-update: ${files.length} migrations → supabase/updates/RUN_THIS_UPDATE.sql`);
